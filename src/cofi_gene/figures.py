"""Week 7 figures with a dependency-free SVG backend.

The three figures required by ``AGENTS.md`` §6 are generated from files the runs
already write, never from numbers typed by hand:

1. ``bar_chart``      B0-B7 metric with error bars (upstream AP or downstream DE AP);
2. ``line_chart``     robustness curves (metric vs missing-edge ratio);
3. ``graph_case``     a local feedback case (edge weights before/after).

Rendering SVG in pure Python keeps CI and the CPU laptop free of matplotlib while
still producing a vector figure that Office/PowerPoint can import. PNG/PDF can be
produced by converting that SVG (Inkscape, ``rsvg-convert``, or PowerPoint's
"Save as Picture"), so the repository needs **no** plotting dependency and the
figure stays reproducible from the JSON.

Axis maths is deliberately small and deterministic (fixed tick algorithm, no
random layout), so a figure can be regenerated byte-for-byte from the same JSON.
"""

from __future__ import annotations

import html
import json
import math
from pathlib import Path

__all__ = [
    "SUPPORTED_FORMATS",
    "bar_chart",
    "line_chart",
    "graph_case",
    "load_json",
]

SUPPORTED_FORMATS = ("svg",)

_PALETTE = ("#2E86C1", "#E67E22", "#27AE60", "#8E44AD", "#C0392B",
            "#16A085", "#7F8C8D", "#D4AC0D")


def _f(value: float) -> str:
    """Compact number formatting for SVG attributes (3 decimals is plenty)."""
    if value == int(value):
        return str(int(value))
    return f"{value:.3f}".rstrip("0").rstrip(".")


def _escape(text) -> str:
    return html.escape(str(text), quote=True)


def load_json(path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _nice_bounds(values: list[float], pad: float = 0.05) -> tuple[float, float]:
    """Data range widened by ``pad``; a flat series gets a symmetric window."""
    finite = [float(value) for value in values if value is not None
              and math.isfinite(float(value))]
    if not finite:
        return 0.0, 1.0
    low, high = min(finite), max(finite)
    if high == low:
        delta = max(0.05, abs(high) * 0.1)
        return low - delta, high + delta
    span = high - low
    return low - span * pad, high + span * pad


def _ticks(low: float, high: float, count: int = 5) -> list[float]:
    """Evenly spaced ticks including both ends (deterministic, no nice-number search)."""
    if high <= low:
        return [low]
    return [low + (high - low) * index / (count - 1) for index in range(count)]


def _scale(value: float, low: float, high: float, out_low: float, out_high: float) -> float:
    if high <= low:
        return (out_low + out_high) / 2.0
    ratio = (float(value) - low) / (high - low)
    return out_low + ratio * (out_high - out_low)


class _Canvas:
    """Tiny SVG element collector (rect/line/circle/text/polyline)."""

    def __init__(self, width: int, height: int) -> None:
        self.width = int(width)
        self.height = int(height)
        self.parts: list[str] = []

    def rect(self, x, y, w, h, fill="#ffffff", stroke=None, rx=0, stroke_width=1,
             opacity=None) -> None:
        extra = f' stroke="{stroke}" stroke-width="{_f(stroke_width)}"' if stroke else ""
        extra += f' opacity="{_f(opacity)}"' if opacity is not None else ""
        self.parts.append(
            f'<rect x="{_f(x)}" y="{_f(y)}" width="{_f(max(w, 0))}" '
            f'height="{_f(max(h, 0))}" rx="{_f(rx)}" fill="{fill}"{extra}/>')

    def line(self, x1, y1, x2, y2, stroke="#333333", width=1, dash=None) -> None:
        extra = f' stroke-dasharray="{dash}"' if dash else ""
        self.parts.append(
            f'<line x1="{_f(x1)}" y1="{_f(y1)}" x2="{_f(x2)}" y2="{_f(y2)}" '
            f'stroke="{stroke}" stroke-width="{_f(width)}"{extra}/>')

    def circle(self, cx, cy, r, fill="#2E86C1", stroke="#ffffff", width=1) -> None:
        self.parts.append(
            f'<circle cx="{_f(cx)}" cy="{_f(cy)}" r="{_f(r)}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{_f(width)}"/>')

    def text(self, x, y, text, size=11, anchor="start", fill="#222222",
             weight="normal", rotate=None) -> None:
        extra = f' transform="rotate({_f(rotate)} {_f(x)} {_f(y)})"' if rotate else ""
        self.parts.append(
            f'<text x="{_f(x)}" y="{_f(y)}" font-family="Helvetica, Arial, sans-serif" '
            f'font-size="{_f(size)}" text-anchor="{anchor}" fill="{fill}" '
            f'font-weight="{weight}"{extra}>{_escape(text)}</text>')

    def polyline(self, points, stroke="#2E86C1", width=2, fill="none") -> None:
        path = " ".join(f"{_f(x)},{_f(y)}" for x, y in points)
        self.parts.append(f'<polyline points="{path}" fill="{fill}" stroke="{stroke}" '
                          f'stroke-width="{_f(width)}"/>')

    def render(self, title: str = "") -> str:
        head = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" '
                f'height="{self.height}" viewBox="0 0 {self.width} {self.height}">')
        title_tag = f"<title>{_escape(title)}</title>" if title else ""
        body = "\n".join(["  " + part for part in self.parts])
        return f"{head}\n{title_tag}\n{body}\n</svg>\n"


def _plot_area(width: float, height: float):
    """Left, top, right, bottom of the plotting rectangle (room for axis text)."""
    return 92.0, 96.0, width - 40.0, height - 96.0


def _draw_frame(canvas: _Canvas, area, low: float, high: float, ylabel: str,
                title: str, note: str | None = None, ticks: int = 5) -> list[tuple]:
    """Title, y-axis, gridlines and tick labels; returns ``[(value, y), ...]``."""
    left, top, right, bottom = area
    canvas.text((left + right) / 2.0, 34, title, size=17, anchor="middle",
                weight="bold")
    if note:
        canvas.text((left + right) / 2.0, 56, note, size=11, anchor="middle",
                    fill="#666666")
    canvas.text(24, (top + bottom) / 2.0, ylabel, size=12, anchor="middle",
                rotate=-90)
    canvas.line(left, bottom, right, bottom, stroke="#555555", width=1.2)
    canvas.line(left, top, left, bottom, stroke="#555555", width=1.2)
    marks = []
    for value in _ticks(low, high, ticks):
        y = _scale(value, low, high, bottom, top)
        canvas.line(left, y, right, y, stroke="#E5E5E5", width=0.8)
        canvas.text(left - 8, y + 4, f"{value:.3f}", size=10, anchor="end",
                    fill="#555555")
        marks.append((value, y))
    return marks


def _legend(canvas: _Canvas, items, y: float, x0: float | None = None) -> None:
    """Coloured squares plus labels, laid out left to right on one line."""
    x = 92.0 if x0 is None else x0
    for index, item in enumerate(items):
        color = item.get("color") or _PALETTE[index % len(_PALETTE)]
        canvas.rect(x, y - 9, 11, 11, fill=color, rx=2)
        canvas.text(x + 16, y + 1, item["label"], size=11)
        x += 34 + 7.4 * len(str(item["label"]))


def _save(canvas: _Canvas, path, title: str) -> dict:
    """Write the SVG and return metadata (format + size) for the caller/tests."""
    path = Path(path)
    if path.suffix.lower() != ".svg":
        raise ValueError(f"only SVG output is supported, got {path.suffix!r}; "
                         "convert the SVG to PNG/PDF afterwards if needed")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(canvas.render(title), encoding="utf-8")
    return {"path": str(path), "format": "svg",
            "width": canvas.width, "height": canvas.height}


def bar_chart(categories, groups, path, title: str = "", ylabel: str = "metric",
              note: str | None = None, fmt: str = "{:.3f}", ylim=None,
              width: int = 900, height: int = 520, rotate_x: bool | None = None) -> dict:
    """Grouped bars with error bars (one bar per group inside each category).

    ``groups`` items are ``{"label", "means", "stds"}``; ``stds`` may be all zero
    (a single-seed diagnostic run) and then no whisker is drawn.
    """
    categories = [str(item) for item in categories]
    if not categories:
        raise ValueError("bar_chart needs at least one category")
    if not groups:
        raise ValueError("bar_chart needs at least one group")
    for group in groups:
        if len(group["means"]) != len(categories) or len(group["stds"]) != len(categories):
            raise ValueError(f"group {group.get('label')!r} must provide one mean and one "
                             f"std per category ({len(categories)})")
    spread = []
    for group in groups:
        for mean, std in zip(group["means"], group["stds"]):
            if mean is None:      # a single-graph model simply has no bar here
                continue
            spread += [float(mean) - float(std or 0.0), float(mean) + float(std or 0.0)]
    if not spread:
        raise ValueError("every value is None; nothing to draw")
    low, high = _nice_bounds(spread)
    if ylim is not None:
        low, high = float(ylim[0]), float(ylim[1])
    canvas = _Canvas(width, height)
    canvas.rect(0, 0, width, height, fill="#ffffff")
    area = _plot_area(width, height)
    left, top, right, bottom = area
    _draw_frame(canvas, area, low, high, ylabel, title, note)
    _legend(canvas, [{"label": group["label"]} for group in groups], y=76)
    slot = (right - left) / len(categories)
    inner = slot * 0.72
    bar_width = inner / len(groups)
    rotate = rotate_x if rotate_x is not None else (len(categories) > 8)
    show_values = len(categories) * len(groups) <= 24
    for index, category in enumerate(categories):
        centre = left + slot * (index + 0.5)
        start = centre - inner / 2.0
        for group_index, group in enumerate(groups):
            if group["means"][index] is None:
                continue
            mean = float(group["means"][index])
            std = float(group["stds"][index] or 0.0)
            x = start + bar_width * group_index + bar_width * 0.08
            bar = bar_width * 0.84
            y = _scale(mean, low, high, bottom, top)
            color = _PALETTE[group_index % len(_PALETTE)]
            canvas.rect(x, y, bar, bottom - y, fill=color, rx=2, opacity=0.92)
            if std > 0.0:
                y_low = _scale(mean - std, low, high, bottom, top)
                y_high = _scale(mean + std, low, high, bottom, top)
                cx = x + bar / 2.0
                canvas.line(cx, y_low, cx, y_high, stroke="#333333", width=1.2)
                canvas.line(cx - 4, y_low, cx + 4, y_low, stroke="#333333", width=1.2)
                canvas.line(cx - 4, y_high, cx + 4, y_high, stroke="#333333", width=1.2)
            if show_values:
                canvas.text(x + bar / 2.0, y - 5, fmt.format(mean), size=9,
                            anchor="middle", fill="#333333")
        label_y = bottom + 20
        if rotate:
            canvas.text(centre, label_y, category, size=11, anchor="end", rotate=-28)
        else:
            canvas.text(centre, label_y, category, size=11, anchor="middle")
    return _save(canvas, path, title) | {
        "categories": categories,
        "groups": [group["label"] for group in groups],
        "y_range": [low, high],
    }


def line_chart(x_values, series, path, title: str = "", xlabel: str = "",
               ylabel: str = "metric", note: str | None = None,
               x_fmt: str = "{:.2f}", ylim=None, width: int = 900,
               height: int = 520) -> dict:
    """One polyline per series with markers (robustness curves)."""
    xs = [float(value) for value in x_values]
    if not xs:
        raise ValueError("line_chart needs at least one x value")
    if not series:
        raise ValueError("line_chart needs at least one series")
    for item in series:
        if len(item["ys"]) != len(xs):
            raise ValueError(f"series {item.get('label')!r} must provide one y per x "
                             f"({len(xs)})")
    values = [float(value) for item in series for value in item["ys"]]
    low, high = _nice_bounds(values)
    if ylim is not None:
        low, high = float(ylim[0]), float(ylim[1])
    canvas = _Canvas(width, height)
    canvas.rect(0, 0, width, height, fill="#ffffff")
    area = _plot_area(width, height)
    left, top, right, bottom = area
    _draw_frame(canvas, area, low, high, ylabel, title, note)
    _legend(canvas, [{"label": item["label"]} for item in series], y=76)
    x_low, x_high = min(xs), max(xs)
    rotate = len(xs) > 8

    def to_x(value: float) -> float:
        return _scale(value, x_low, x_high, left + 20, right - 20)

    for value in xs:
        x = to_x(value)
        canvas.line(x, bottom, x, bottom + 5, stroke="#555555", width=1)
        label = x_fmt.format(value)
        if rotate:
            canvas.text(x, bottom + 20, label, size=10, anchor="end", rotate=-28)
        else:
            canvas.text(x, bottom + 20, label, size=10, anchor="middle")
    canvas.text((left + right) / 2.0, bottom + 58, xlabel, size=12, anchor="middle")
    for index, item in enumerate(series):
        color = _PALETTE[index % len(_PALETTE)]
        points = [(to_x(x), _scale(float(y), low, high, bottom, top))
                  for x, y in zip(xs, item["ys"])]
        if len(points) > 1:
            canvas.polyline(points, stroke=color, width=2.2)
        for x, y in points:
            canvas.circle(x, y, 3.4, fill=color)
    return _save(canvas, path, title) | {"series": [item["label"] for item in series],
                                         "x_values": xs, "y_range": [low, high]}

def graph_case(case: dict, path, title: str = "Graph feedback case",
               note: str | None = None, width: int = 960, height: int = 620,
               max_edges: int = 16, panel_rows: int = 8) -> dict:
    """Draw a local feedback case: node circle + edges coloured/weighted by Δw.

    ``case`` comes from ``scripts/export_feedback_case.py`` and must contain
    ``edges`` with ``u_id``/``v_id``, ``weight_before``, ``weight_after`` and
    ``delta``. Edge width is proportional to the *new* weight; red means the edge
    was up-weighted, blue means down-weighted. A side panel lists the largest
    changes so the figure stays readable when the case has many edges.
    """
    edges = list(case.get("edges") or [])
    if not edges:
        raise ValueError("graph_case needs at least one edge")
    for edge in edges:
        for key in ("weight_before", "weight_after", "delta"):
            if key not in edge:
                raise ValueError(f"edge {edge.get('u_id')}–{edge.get('v_id')} "
                                 f"lacks {key!r}")
    node_ids: list[str] = []
    for edge in edges:
        for key in ("u_id", "v_id"):
            if edge[key] not in node_ids:
                node_ids.append(edge[key])
    if len(node_ids) > max_edges + 2:
        node_ids = node_ids[: max_edges + 2]
    shown = [edge for edge in edges
             if edge["u_id"] in node_ids and edge["v_id"] in node_ids]
    shown.sort(key=lambda edge: abs(float(edge["delta"])))
    shown = shown[-max_edges:]
    drawn_nodes = [node for node in node_ids
                   if any(node in (edge["u_id"], edge["v_id"]) for edge in shown)]
    if not drawn_nodes:  # pragma: no cover - guarded by the empty-edge check above
        raise ValueError("no drawable nodes left after filtering the edges")

    canvas = _Canvas(width, height)
    canvas.rect(0, 0, width, height, fill="#ffffff")
    canvas.text(width / 2.0, 34, title, size=17, anchor="middle", weight="bold")
    channel = case.get("channel", "?")
    summary = case.get("summary") or {}
    caption = note or (f"channel {channel} · {len(edges)} candidate edges · "
                       f"{summary.get('n_up', '?')} up / "
                       f"{summary.get('n_down', '?')} down")
    canvas.text(width / 2.0, 56, caption, size=11, anchor="middle", fill="#666666")

    cx, cy, radius = 300.0, 340.0, 190.0
    positions = {}
    for index, node in enumerate(drawn_nodes):
        angle = -math.pi / 2.0 + 2.0 * math.pi * index / max(1, len(drawn_nodes))
        positions[node] = (cx + radius * math.cos(angle), cy + radius * math.sin(angle))
    max_weight = max(float(edge["weight_after"]) for edge in shown) or 1.0
    for edge in shown:
        start = positions[edge["u_id"]]
        stop = positions[edge["v_id"]]
        delta = float(edge["delta"])
        color = "#C0392B" if delta > 0 else ("#2471A3" if delta < 0 else "#95A5A6")
        stroke = 1.0 + 7.0 * float(edge["weight_after"]) / max_weight
        canvas.line(start[0], start[1], stop[0], stop[1], stroke=color, width=stroke)
    for node in drawn_nodes:
        x, y = positions[node]
        canvas.circle(x, y, 17, fill="#F4F6F7", stroke="#34495E", width=1.4)
        label = str(node)
        canvas.text(x, y + 3.5, label if len(label) <= 7 else label[:6] + "…",
                    size=9, anchor="middle", fill="#1B2631")

    _legend(canvas, [{"label": "up-weighted", "color": "#C0392B"},
                     {"label": "down-weighted", "color": "#2471A3"}], y=height - 34)
    canvas.text(92, height - 14, "edge width ∝ weight after feedback", size=10,
                fill="#666666")

    panel_x = 600.0
    canvas.text(panel_x, 110, f"top {panel_rows} |Δw| changes", size=12, weight="bold")
    canvas.text(panel_x, 132, "pair", size=10, fill="#666666")
    canvas.text(panel_x + 150, 132, "before → after", size=10, fill="#666666")
    canvas.text(panel_x + 300, 132, "Δ", size=10, fill="#666666")
    for row, edge in enumerate(reversed(shown[-panel_rows:])):
        y = 156 + row * 24
        pair = f"{edge['u_id']}–{edge['v_id']}"
        canvas.text(panel_x, y, pair if len(pair) <= 18 else pair[:17] + "…", size=10)
        canvas.text(panel_x + 150, y,
                    f"{float(edge['weight_before']):.3f} → "
                    f"{float(edge['weight_after']):.3f}", size=10)
        color = "#C0392B" if float(edge["delta"]) > 0 else "#2471A3"
        canvas.text(panel_x + 300, y, f"{float(edge['delta']):+.3f}", size=10,
                    fill=color)
    return _save(canvas, path, title) | {"nodes": drawn_nodes,
                                         "edges_drawn": len(shown),
                                         "channel": channel}

